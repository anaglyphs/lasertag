		private void DrawFooter()
		{
			EditorGUILayout.BeginHorizontal(EditorStyles.toolbar);

			int materialCount = groups.Sum(g => g.materials.Count);
			GUILayout.Label($"{targets.Count} assets · {groups.Count} types · {materialCount} materials",
				EditorStyles.miniLabel);

			GUILayout.FlexibleSpace();

			if (GUILayout.Button("Save Assets", EditorStyles.toolbarButton, GUILayout.Width(90)))
				AssetDatabase.SaveAssets();

			EditorGUILayout.EndHorizontal();
		}
